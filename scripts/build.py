#!/usr/bin/env python3
"""Build Turtle, JSON-LD and Markdown views from the CSV sources.

Sources (edit these):  vocab/*.csv, taxonomy/audiences.csv
Outputs (generated):   vocab/*.ttl, vocab/*.jsonld, taxonomy/audiences.ttl,
                       taxonomy/audiences.jsonld, taxonomy/AUDIENCES.md

Python 3.10+, standard library only:  python3 -I scripts/build.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://health-culture.org/vocab/"
LVL = BASE + "ecological-levels/"
CDC = BASE + "cdc-sem-levels/"
AUD = BASE + "audiences/"
LICENSE = "https://creativecommons.org/licenses/by/4.0/"
MESH = "http://id.nlm.nih.gov/mesh/"
LRMI = "http://purl.org/dcx/lrmi-vocabs/educationalAudienceRole/"
SL = "https://sleepliteracy.org/"
SCHEMA = "https://schema.org/"
TAAG = "https://cancercontrol.cancer.gov/sites/default/files/2020-06/theory.pdf"
MCLEROY = "https://doi.org/10.1177/109019818801500401"
CDC_PAGE = "https://www.cdc.gov/violence-prevention/about/index.html"

PREFIXES = """@prefix skos: <http://www.w3.org/2004/02/skos/core#> .
@prefix dct: <http://purl.org/dc/terms/> .
@prefix schema: <https://schema.org/> .
"""
HEADER = "# Generated by scripts/build.py from the CSV next to it. Do not edit by hand.\n# Draft: IRIs under health-culture.org/vocab/ are placeholders until a public home is chosen.\n\n"

CONTEXT = {
    "skos": "http://www.w3.org/2004/02/skos/core#",
    "dct": "http://purl.org/dc/terms/",
    "schema": SCHEMA,
    "id": "@id",
    "type": "@type",
    "prefLabel": {"@id": "skos:prefLabel", "@language": "en"},
    "altLabel": {"@id": "skos:altLabel", "@language": "en", "@container": "@set"},
    "definition": {"@id": "skos:definition", "@language": "en"},
    "scopeNote": {"@id": "skos:scopeNote", "@language": "en"},
    "example": {"@id": "skos:example", "@language": "en"},
    "editorialNote": {"@id": "skos:editorialNote", "@language": "en"},
    "notation": "skos:notation",
    "inScheme": {"@id": "skos:inScheme", "@type": "@id"},
    "topConceptOf": {"@id": "skos:topConceptOf", "@type": "@id"},
    "broader": {"@id": "skos:broader", "@type": "@id"},
    "related": {"@id": "skos:related", "@type": "@id", "@container": "@set"},
    "closeMatch": {"@id": "skos:closeMatch", "@type": "@id", "@container": "@set"},
    "broadMatch": {"@id": "skos:broadMatch", "@type": "@id", "@container": "@set"},
    "relatedMatch": {"@id": "skos:relatedMatch", "@type": "@id", "@container": "@set"},
    "exactMatch": {"@id": "skos:exactMatch", "@type": "@id", "@container": "@set"},
    "source": {"@id": "dct:source", "@type": "@id", "@container": "@set"},
    "title": {"@id": "dct:title", "@language": "en"},
    "license": {"@id": "dct:license", "@type": "@id"},
}


def lit(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"@en'


def read(path):
    with open(ROOT / path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def split(s):
    return [x.strip() for x in (s or "").split("|") if x.strip()]


def ttl_concept(iri, props):
    lines = [f"<{iri}> a skos:Concept"]
    for p, vals in props:
        for v in vals if isinstance(vals, list) else [vals]:
            if v:
                lines.append(f"  {p} {v}")
    return " ;\n".join(lines) + " .\n"


def write(path, text):
    (ROOT / path).write_text(text, encoding="utf-8")
    print("wrote", path)


def jsonld(path, graph):
    write(path, json.dumps({"@context": CONTEXT, "@graph": graph}, indent=2, ensure_ascii=False) + "\n")


def mesh_ids(s):
    # "D009272 Persons|D000293 Adolescent" -> ["D009272", ...]
    return [x.split()[0] for x in split(s)]


# ---------------------------------------------------------------- levels
def build_levels():
    rows = read("vocab/ecological-levels.csv")
    cdc = read("vocab/cdc-sem-levels.csv")
    scheme = LVL
    out = [PREFIXES, HEADER,
           f"<{scheme}> a skos:ConceptScheme ;\n  dct:title {lit('Ecological levels of influence')} ;\n"
           f"  dct:description {lit('The five levels of influence on health behavior from McLeroy, Bibeau, Steckler and Glanz (1988), as presented in NCI Theory at a Glance (2005), Table 1. Plain-language labels and definitions by Health Culture Foundation.')} ;\n"
           f"  dct:source <{MCLEROY}>, <{TAAG}> ;\n  dct:license <{LICENSE}> ;\n"
           f"  skos:hasTopConcept {', '.join(f'<{LVL}{r['id']}>' for r in rows)} .\n\n"]
    graph = [{"id": scheme, "type": "skos:ConceptScheme", "title": "Ecological levels of influence", "license": LICENSE,
              "source": [MCLEROY, TAAG]}]
    for r in rows:
        iri = LVL + r["id"]
        out.append(ttl_concept(iri, [
            ("skos:inScheme", f"<{scheme}>"), ("skos:topConceptOf", f"<{scheme}>"),
            ("skos:notation", f'"{r["notation"]}"'),
            ("skos:prefLabel", lit(r["pref_label"])),
            ("skos:altLabel", [lit(r["plain_label"])] + [lit(a) for a in split(r["alt_labels"])]),
            ("skos:definition", lit(r["definition"])),
            ("skos:note", lit(f'NCI Theory at a Glance (2005), Table 1: "{r["source_definition"]}"')),
            ("skos:scopeNote", lit(r["scope_note"])),
            ("skos:example", lit(r["sleep_example"])),
            ("dct:source", [f"<{TAAG}>", f"<{MCLEROY}>"]),
        ]))
        graph.append({"id": iri, "type": "skos:Concept", "inScheme": scheme, "topConceptOf": scheme,
                      "notation": r["notation"], "prefLabel": r["pref_label"],
                      "altLabel": [r["plain_label"]] + split(r["alt_labels"]),
                      "definition": r["definition"], "skos:note": f'NCI Theory at a Glance (2005), Table 1: "{r["source_definition"]}"',
                      "scopeNote": r["scope_note"], "example": r["sleep_example"], "source": [TAAG, MCLEROY]})
    write("vocab/ecological-levels.ttl", "".join(out))
    jsonld("vocab/ecological-levels.jsonld", graph)

    scheme = CDC
    out = [PREFIXES, HEADER,
           f"<{scheme}> a skos:ConceptScheme ;\n  dct:title {lit('CDC social-ecological model (four levels)')} ;\n"
           f"  dct:description {lit('The four-level social-ecological model used by CDC violence prevention (after Dahlberg and Krug 2002), paraphrased. CDC publishes no URIs for these levels; HCF mints them here so crosswalks have something to point at.')} ;\n"
           f"  dct:source <{CDC_PAGE}> ;\n  dct:license <{LICENSE}> ;\n"
           f"  skos:hasTopConcept {', '.join(f'<{CDC}{r['id']}>' for r in cdc)} .\n\n"]
    graph = [{"id": scheme, "type": "skos:ConceptScheme", "title": "CDC social-ecological model (four levels)", "license": LICENSE, "source": [CDC_PAGE]}]
    for r in cdc:
        iri = CDC + r["id"]
        out.append(ttl_concept(iri, [
            ("skos:inScheme", f"<{scheme}>"), ("skos:topConceptOf", f"<{scheme}>"),
            ("skos:notation", f'"{r["notation"]}"'), ("skos:prefLabel", lit(r["pref_label"])),
            ("skos:definition", lit(r["definition"])), ("dct:source", f"<{r['source_url']}>"),
        ]))
        graph.append({"id": iri, "type": "skos:Concept", "inScheme": scheme, "topConceptOf": scheme, "notation": r["notation"],
                      "prefLabel": r["pref_label"], "definition": r["definition"], "source": [r["source_url"]]})
    write("vocab/cdc-sem-levels.ttl", "".join(out))
    jsonld("vocab/cdc-sem-levels.jsonld", graph)
    return rows


# ---------------------------------------------------------------- audiences
def build_audiences(levels):
    path = ROOT / "taxonomy/audiences.csv"
    if not path.exists():
        return
    rows = read("taxonomy/audiences.csv")
    ids = {r["id"] for r in rows}
    lvl_ids = {l["id"] for l in levels}
    for r in rows:
        assert r["level"] in lvl_ids, f"{r['id']}: unknown level {r['level']}"
        assert not r["broader"] or r["broader"] in ids, f"{r['id']}: unknown broader {r['broader']}"
        assert r["facet"] in {"role", "population", "organization", "group"}, f"{r['id']}: bad facet {r['facet']}"
    scheme = AUD
    tops = [r for r in rows if not r["broader"]]
    out = [PREFIXES, f"@prefix hcflvl: <{LVL}> .\n", HEADER,
           f"<{scheme}> a skos:ConceptScheme ;\n  dct:title {lit('HCF audiences by ecological level')} ;\n"
           f"  dct:description {lit('Who a health resource is for, or who acts on it, placed at one of the five ecological levels of influence. Version 0.1, draft, unreviewed.')} ;\n"
           f"  dct:license <{LICENSE}> ;\n  schema:version \"0.1\" ;\n"
           f"  skos:hasTopConcept {', '.join(f'<{AUD}{r['id']}>' for r in tops)} .\n\n"]
    graph = [{"id": scheme, "type": "skos:ConceptScheme", "title": "HCF audiences by ecological level", "license": LICENSE, "schema:version": "0.1"}]
    for r in rows:
        iri = AUD + r["id"]
        broader = f"<{AUD}{r['broader']}>" if r["broader"] else None
        mesh = [f"<{MESH}{m}>" for m in mesh_ids(r["mesh"])]
        schema_t = [f"<{SCHEMA}{s}>" for s in split(r["schema_org"])]
        schema_t += [f"<{LRMI}{x}>" for x in split(r["lrmi_role"])]
        props = [("skos:inScheme", f"<{scheme}>"), ("skos:topConceptOf", None if broader else f"<{scheme}>"),
                 ("skos:broader", broader), ("skos:prefLabel", lit(r["pref_label"])),
                 ("skos:altLabel", [lit(a) for a in split(r["alt_labels"])]),
                 ("skos:definition", lit(r["definition"])),
                 ("skos:example", lit(r["sleep_example"]) if r["sleep_example"] else None),
                 ("skos:related", f"hcflvl:{r['level']}"),
                 ("skos:closeMatch", mesh + schema_t),
                 ("skos:editorialNote", lit(r["notes"]) if r["notes"] else None)]
        out.append(ttl_concept(iri, props))
        node = {"id": iri, "type": "skos:Concept", "inScheme": scheme, "prefLabel": r["pref_label"],
                "definition": r["definition"], "related": [LVL + r["level"]],
                "hcf:facet": r["facet"]}
        if broader:
            node["broader"] = AUD + r["broader"]
        else:
            node["topConceptOf"] = scheme
        if split(r["alt_labels"]):
            node["altLabel"] = split(r["alt_labels"])
        if r["sleep_example"]:
            node["example"] = r["sleep_example"]
        cm = [MESH + m for m in mesh_ids(r["mesh"])] + [SCHEMA + s for s in split(r["schema_org"])]
        if cm:
            node["closeMatch"] = cm
        if split(r["lrmi_role"]):
            node["closeMatch"] = node.get("closeMatch", []) + [LRMI + x for x in split(r["lrmi_role"])]
        if split(r["eric"]):
            node["hcf:ericAudience"] = split(r["eric"])
        if r["notes"]:
            node["editorialNote"] = r["notes"]
        graph.append(node)
    ctx_extra = {"hcf": BASE + "terms#"}
    write("taxonomy/audiences.ttl", "".join(out))
    (ROOT / "taxonomy/audiences.jsonld").write_text(json.dumps({"@context": [CONTEXT, ctx_extra], "@graph": graph}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote taxonomy/audiences.jsonld")
    write("taxonomy/AUDIENCES.md", markdown(levels, rows))
    build_crosswalks(rows)


SEED = __import__("re").compile(r"^([a-z-]+)/([a-z0-9-]+) \((exact|close|broad|narrow|related)\)$")


def seeds_of(r):
    out = []
    for s in split(r["sleepliteracy_seed"]):
        m = SEED.match(s)
        assert m, f"{r['id']}: bad seed {s!r}"
        out.append(m.groups())
    return out


def sssom(path, title, prefixes, comment, rows):
    head = ["# curie_map:"] + [f"#   {k}: {v}" for k, v in prefixes.items()] + [
        "#   skos: http://www.w3.org/2004/02/skos/core#", "#   semapv: https://w3id.org/semapv/vocab/",
        f"# mapping_set_id: https://github.com/vivwebsolutions/HCF-Audiences-Ecological-Model-2.0/{path}",
        "# mapping_set_version: 2026-10-22", f"# mapping_set_title: {title}",
        "# license: https://creativecommons.org/licenses/by/4.0/",
        "# creator_label:", "#   - Claude (Claude Code), for Health Culture Foundation; not yet reviewed by a person",
        f"# comment: {comment} Generated by scripts/build.py from taxonomy/audiences.csv; edit the CSV, not this file."]
    cols = ["subject_id", "subject_label", "predicate_id", "object_id", "object_label", "mapping_justification", "author_label", "mapping_date", "comment"]
    lines = head + ["\t".join(cols)] + ["\t".join(x) for x in rows]
    write(path, "\n".join(lines) + "\n")


def build_crosswalks(rows):
    J = "semapv:ManualMappingCuration"
    A, D = "Claude (unreviewed)", "2026-10-22"
    mesh, lrmi, sl = [], [], []
    for r in rows:
        subj = "hcfaud:" + r["id"]
        for m in split(r["mesh"]):
            uid, _, label = m.partition(" ")
            mesh.append([subj, r["pref_label"], "skos:closeMatch" if r["facet"] == "population" else "skos:relatedMatch", "MESH:" + uid, label, J, A, D,
                         "Population: who the content is about." if r["facet"] == "population" else "MeSH says what an article is about, not who reads it."])
        for x in split(r["lrmi_role"]):
            pred = "skos:exactMatch" if x in ("parent", "mentor", "peerTutor", "teacher", "student", "administrator", "generalPublic") and len(split(r["lrmi_role"])) == 1 else "skos:broadMatch" if x == "professional" else "skos:closeMatch"
            lrmi.append([subj, r["pref_label"], pred, "audRole:" + x, x, J, A, D, ""])
        for tax, slug, pred in seeds_of(r):
            sl.append([f"sl:{tax}/{slug}", slug, f"skos:{pred}Match", subj, r["pref_label"], J, A, D, ""])
    hcf = {"hcfaud": AUD}
    sssom("crosswalks/audiences-to-mesh.sssom.tsv", "HCF audiences to MeSH", {**hcf, "MESH": MESH},
          "Populations use closeMatch; roles and organizations use relatedMatch because MeSH is a subject vocabulary. All UIDs checked against id.nlm.nih.gov/mesh/lookup on 2026-10-22 (MeSH 2026). MeSH is produced by the U.S. National Library of Medicine; no NLM endorsement is implied.", mesh)
    sssom("crosswalks/audiences-to-lrmi.sssom.tsv", "HCF audiences to LRMI Educational Audience Role", {**hcf, "audRole": LRMI},
          "LRMI has 8 roles. Health roles map broadMatch to audRole:professional.", lrmi)
    sssom("crosswalks/sleepliteracy-to-audiences.sssom.tsv", "SleepLiteracy.org audience terms to HCF audiences", {"sl": SL + "taxonomy/", **hcf},
          "Subjects are SleepLiteracy WordPress terms as taxonomy/slug (taxonomies audience, upper-lvl-audience, organization-audience; pulled from the REST API 2026-10-22). Grouping-only terms (by-age, by-gender, by-identity-or-community) and pro2pro, special-populations have no mapping yet; see OPEN-QUESTIONS.md.", sl)


def markdown(levels, rows):
    kids = {}
    for r in rows:
        kids.setdefault(r["broader"], []).append(r)
    md = ["# Audiences by ecological level (v0.1)", "",
          "_Generated by `scripts/build.py` from [`audiences.csv`](audiences.csv). Draft; nothing here has been reviewed by a person yet._", "",
          "Each audience is placed at the level where it **acts**: a parent acts on a child's sleep through the relationship (level 2), a principal through the school's rules (level 3). "
          "**Population** entries (life stages and situations) describe who a resource is *about*; combine one with a role, e.g. *parents and caregivers* + *teens*.", "",
          f"{len(rows)} concepts. Facets: role = a person acting in a role; organization = a kind of organization; group = a collective; population = who it is about.", ""]
    for l in levels:
        at = [r for r in rows if r["level"] == l["id"] and (not r["broader"] or next(x for x in rows if x["id"] == r["broader"])["level"] != l["id"])]
        md += [f"## {l['notation']}. {l['plain_label']} ({l['pref_label'].lower()})", "", f"_{l['definition']}_", ""]
        if not at:
            md += ["_No audiences yet._", ""]
            continue
        md += ["| Audience | Facet | Definition | Also called | Maps to |", "|---|---|---|---|---|"]

        def emit(r, depth):
            maps = [f"MeSH {m}" for m in split(r["mesh"])] + [f"schema:{s}" for s in split(r["schema_org"])]
            maps += [f"LRMI {x}" for x in split(r["lrmi_role"])]
            maps += [f"ERIC \"{x}\"" for x in split(r["eric"])]
            name = ("&nbsp;&nbsp;&nbsp;&nbsp;" * depth) + ("↳ " if depth else "") + f"**{r['pref_label']}**"
            md.append(f"| {name} | {r['facet']} | {r['definition']} | {', '.join(split(r['alt_labels']))} | {'; '.join(maps)} |")
            for k in kids.get(r["id"], []):
                if k["level"] == l["id"]:
                    emit(k, depth + 1)
        for r in at:
            emit(r, 0)
        md.append("")
    seeds = [r for r in rows if r["sleepliteracy_seed"]]
    md += ["## Where the SleepLiteracy tags went", "",
           "Generated from the same CSV as [`crosswalks/sleepliteracy-to-audiences.sssom.tsv`](../crosswalks/sleepliteracy-to-audiences.sssom.tsv). "
           "The match type reads from SleepLiteracy's side: *broad* means the HCF concept is broader.", "",
           "| SleepLiteracy term | HCF audience (match) | Level |", "|---|---|---|"]
    for r in seeds:
        for tax, slug, pred in seeds_of(r):
            md.append(f"| `{tax}/{slug}` | {r['pref_label']} ({pred}) | {r['level']} |")
    md.append("")
    return "\n".join(md)


if __name__ == "__main__":
    build_audiences(build_levels())
